"use client";

/**
 * Issue invoice form (Phase 9 PR-7).
 *
 * Used on /billing/new/[tenant_id]. Pre-populated with tenant_id from
 * props. Shows a live total_myr = subtotal + tax computation.
 * Calls POST /api/admin/billing/invoices on submit.
 *
 * On success redirects to the new invoice's detail page via router.push.
 */

import { useState } from "react";
import { useRouter } from "next/navigation";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Card } from "@/components/ui/card";
import { adminFetch } from "@/lib/api/client";
import { adminRoutes } from "@/lib/api/routes";
import { ApiError } from "@/lib/api/error";
import { formatMyr } from "@/lib/format";
import type { TenantInvoice } from "@/lib/types/billing";

type InvoiceKind = TenantInvoice["invoice_kind"];

const KIND_LABELS: Record<InvoiceKind, string> = {
  monthly_subscription: "Monthly Subscription",
  annual_subscription: "Annual Subscription",
  plan_change_proration: "Plan Change Proration",
  addon_seat: "Add-on Seat",
};

interface Props {
  tenantId: string;
}

export function IssueInvoiceForm({ tenantId }: Props) {
  const router = useRouter();

  const [kind, setKind] = useState<InvoiceKind>("monthly_subscription");
  const [periodStart, setPeriodStart] = useState("");
  const [periodEnd, setPeriodEnd] = useState("");
  const [subtotal, setSubtotal] = useState("");
  const [tax, setTax] = useState("0");
  const [dueAt, setDueAt] = useState("");

  const [isPending, setIsPending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const subtotalNum = parseFloat(subtotal) || 0;
  const taxNum = parseFloat(tax) || 0;
  const totalNum = subtotalNum + taxNum;

  const isProration = kind === "plan_change_proration";

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    setIsPending(true);
    setError(null);
    try {
      const res = await adminFetch<TenantInvoice>(
        adminRoutes.billing.issueInvoice(),
        {
          method: "POST",
          body: {
            tenant_id: tenantId,
            invoice_kind: kind,
            period_start: periodStart,
            period_end: periodEnd,
            subtotal_myr: subtotalNum,
            tax_myr: taxNum,
            due_at: dueAt,
          },
        },
      );
      if (res) {
        router.push(`/billing/${res.id}`);
      }
    } catch (err) {
      if (err instanceof ApiError) {
        setError(err.message);
      } else {
        setError("Unexpected error");
      }
    } finally {
      setIsPending(false);
    }
  }

  return (
    <Card className="space-y-5 p-6">
      <form onSubmit={handleSubmit} className="space-y-5">
        {/* Invoice kind */}
        <div className="space-y-1.5">
          <Label htmlFor="invoice-kind">Invoice kind</Label>
          <select
            id="invoice-kind"
            value={kind}
            onChange={(e) => setKind(e.target.value as InvoiceKind)}
            className="flex h-9 w-full rounded-md border border-input bg-transparent px-3 py-1 text-sm shadow-sm focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-ring"
          >
            {(Object.keys(KIND_LABELS) as InvoiceKind[]).map((k) => (
              <option key={k} value={k}>
                {KIND_LABELS[k]}
              </option>
            ))}
          </select>
        </div>

        {/* Proration notice */}
        {isProration && (
          <div className="rounded-md border border-border bg-muted/40 px-4 py-3 text-sm text-muted-foreground">
            Proration invoices are normally auto-generated by the plan-change
            approval flow. Issue manually only when correcting a discrepancy.
          </div>
        )}

        {/* Period */}
        <div className="grid grid-cols-2 gap-4">
          <div className="space-y-1.5">
            <Label htmlFor="period-start">Period start</Label>
            <Input
              id="period-start"
              type="date"
              required
              value={periodStart}
              onChange={(e) => setPeriodStart(e.target.value)}
            />
          </div>
          <div className="space-y-1.5">
            <Label htmlFor="period-end">Period end</Label>
            <Input
              id="period-end"
              type="date"
              required
              value={periodEnd}
              onChange={(e) => setPeriodEnd(e.target.value)}
            />
          </div>
        </div>

        {/* Amounts */}
        <div className="grid grid-cols-2 gap-4">
          <div className="space-y-1.5">
            <Label htmlFor="subtotal">Subtotal (MYR)</Label>
            <Input
              id="subtotal"
              type="number"
              min={0}
              step="0.01"
              required
              placeholder="e.g. 2499.00"
              value={subtotal}
              onChange={(e) => setSubtotal(e.target.value)}
            />
          </div>
          <div className="space-y-1.5">
            <Label htmlFor="tax">
              Tax (MYR){" "}
              <span className="text-xs text-muted-foreground">(default 0)</span>
            </Label>
            <Input
              id="tax"
              type="number"
              min={0}
              step="0.01"
              value={tax}
              onChange={(e) => setTax(e.target.value)}
            />
          </div>
        </div>

        {/* Computed total */}
        <div className="rounded-md bg-muted/50 px-4 py-3 text-sm">
          <span className="text-muted-foreground">Total: </span>
          <span className="font-semibold font-mono">{formatMyr(totalNum)}</span>
        </div>

        {/* Due date */}
        <div className="space-y-1.5">
          <Label htmlFor="due-at">Due date</Label>
          <Input
            id="due-at"
            type="date"
            required
            value={dueAt}
            onChange={(e) => setDueAt(e.target.value)}
          />
        </div>

        {error && <p className="text-sm text-destructive">{error}</p>}

        <Button type="submit" disabled={isPending}>
          {isPending ? "Issuing…" : "Issue invoice"}
        </Button>
      </form>
    </Card>
  );
}
