"""Tenant-secret encryption — PR-2 implementation (uses nacl.secret.Aead).

Algorithm: XChaCha20-Poly1305 with associated data (AEAD).

- 256-bit key from POLARIS_KMS_KEY (hex-encoded 64 chars → 32 bytes).
- 192-bit (24-byte) nonce per message, auto-generated by `Aead.encrypt`.
- AAD = b"polaris.tenant_secret:v1:" + tenant_id.bytes — binds the ciphertext
  to the tenant so a row copied between tenants fails to decrypt.

Wire format on the bytes returned by encrypt():
    [version: 1 byte = 0x01]
    [Aead.EncryptedMessage: nonce(24) || ciphertext || tag(16)]

PyNaCl's `nacl.secret.Aead` is the high-level, audited wrapper around
libsodium's `crypto_aead_xchacha20poly1305_ietf_*` primitives. Search-first
(2026-05-16) confirmed this is the idiomatic API — the earlier draft of this
module called `nacl.bindings.*` directly, which exposed more surface than
necessary for no benefit.

Caching: the Aead instance is built once per process via `functools.cache`
on `_get_aead()`. Without the cache, every `encrypt`/`decrypt` re-read the
hex key from `os.environ`, re-decoded it, and constructed a fresh Aead —
unnecessary work on the hot path and more places the key touches process
memory. Tests call `_get_aead.cache_clear()` between key-changing fixtures.

Version-byte registry (per ADR-on-deck):
  0x01 — XChaCha20-Poly1305 IETF, 24B nonce, 16B tag, AAD = above prefix
         + tenant_id.bytes (16B).
  0x02 — reserved for future algorithm rotation. Migration path: dual-read
         period where decrypt accepts both versions; encrypt switches to new;
         background re-encrypt of existing rows.

Phase 1 wires this to a `tenant_secrets` table; Phase 0 ships the primitive
only (no DB writes).

CATASTROPHIC RISK: regenerating POLARIS_KMS_KEY post-Phase-1 makes every
existing row undecryptable. Phase 1 startup checks a sentinel in
`platform_health` (Q21 — resolved 2026-05-15) and aborts boot on mismatch.
The lifespan startup gate in `main.py` already refuses to boot non-local
environments without the key being present.
"""

from __future__ import annotations

import os
from functools import cache
from uuid import UUID

import asyncpg
import nacl.exceptions
from nacl.secret import Aead

KEY_BYTES = Aead.KEY_SIZE  # 32
NONCE_BYTES = Aead.NONCE_SIZE  # 24
MAC_BYTES = Aead.MACBYTES  # 16
VERSION = 0x01
AAD_PREFIX = b"polaris.tenant_secret:v1:"

# Platform-scoped AAD for the KMS sentinel in platform_health. Not
# tenant-bound — used only by services/kms_sentinel.py to encrypt/decrypt
# the single boot-time fingerprint row. Keeping the AAD distinct from the
# tenant prefix prevents a sentinel ciphertext from ever round-tripping
# through `decrypt(_, tenant_id)` and vice versa.
PLATFORM_SENTINEL_AAD = b"polaris.platform.kms_sentinel:v1"

# Algo name persisted in tenant_secrets.algo. Single value at GA;
# rotation strategy is "ship a new VERSION byte, accept both during
# the dual-read window, then re-encrypt all rows under the new algo".
ALGO_XCHACHA20POLY1305 = "xchacha20poly1305"


class CryptoError(Exception):
    """Raised on tampered ciphertext, AAD mismatch, missing/bad key, or version skew.

    Messages are intentionally generic so error-handling paths in callers
    don't leak structural information (e.g. key length, oracle distinction
    between tag-failure and AAD-failure). Detailed reasons go to DEBUG logs.
    """


def _load_key() -> bytes:
    """Read POLARIS_KMS_KEY (hex) and return raw 32-byte key.

    Raises CryptoError with a generic message on any failure. Detailed
    failure mode (missing / non-hex / wrong length) is suppressed to avoid
    leaking key-length expectations through error responses.
    """
    raw = os.environ.get("POLARIS_KMS_KEY", "")
    if not raw:
        raise CryptoError("POLARIS_KMS_KEY is not set")
    try:
        key = bytes.fromhex(raw.strip())
    except ValueError as exc:
        # Generic message; the inner ValueError is chained for DEBUG-level logs.
        raise CryptoError("POLARIS_KMS_KEY invalid") from exc
    if len(key) != KEY_BYTES:
        # Don't reveal expected length — generic.
        raise CryptoError("POLARIS_KMS_KEY invalid") from None
    return key


def _aad(tenant_id: UUID) -> bytes:
    return AAD_PREFIX + tenant_id.bytes


@cache
def _get_aead() -> Aead:
    """Singleton Aead instance bound to the current POLARIS_KMS_KEY.

    Cached for the lifetime of the process. Tests that mutate the env var
    must call `_get_aead.cache_clear()` (the test fixture does this
    automatically).
    """
    return Aead(_load_key())


def encrypt(plaintext: bytes, tenant_id: UUID) -> bytes:
    """Encrypt plaintext for the given tenant. Returns versioned wire bytes."""
    if not isinstance(plaintext, (bytes, bytearray)):
        raise CryptoError("plaintext must be bytes")
    try:
        encrypted = _get_aead().encrypt(bytes(plaintext), _aad(tenant_id))
    except nacl.exceptions.CryptoError as exc:
        raise CryptoError("encrypt failed") from exc
    # encrypted is an EncryptedMessage (bytes subclass) shaped as nonce||ct||tag.
    return bytes([VERSION]) + bytes(encrypted)


def decrypt(ciphertext: bytes, tenant_id: UUID) -> bytes:
    """Decrypt previously-encrypted bytes. Raises CryptoError on any failure."""
    if not isinstance(ciphertext, (bytes, bytearray)):
        raise CryptoError("ciphertext must be bytes")
    # Need at least: 1 (version) + nonce + tag, plus any plaintext bytes.
    if len(ciphertext) < 1 + NONCE_BYTES + MAC_BYTES:
        raise CryptoError("ciphertext too short")
    if ciphertext[0] != VERSION:
        # Don't echo the bad byte — generic message.
        raise CryptoError("unsupported ciphertext version")
    body = bytes(ciphertext[1:])
    try:
        return _get_aead().decrypt(body, _aad(tenant_id))
    except nacl.exceptions.CryptoError as exc:
        # Generic message — never leak whether failure was tag-mismatch vs AAD
        # vs corruption (no oracle).
        raise CryptoError("decrypt failed") from exc


def health_check() -> bool:
    """Return True iff POLARIS_KMS_KEY is set and decodes to 32 bytes."""
    try:
        _load_key()
    except CryptoError:
        return False
    return True


# ---------------------------------------------------------------------------
# Platform-sentinel primitives (PR-3) — used only by services/kms_sentinel.py
# ---------------------------------------------------------------------------


def encrypt_platform_sentinel(plaintext: bytes) -> bytes:
    """Encrypt a platform-scoped value (not tenant-bound). AAD is the fixed
    `PLATFORM_SENTINEL_AAD` constant. Returns versioned wire bytes in the
    same shape as `encrypt()`."""
    if not isinstance(plaintext, (bytes, bytearray)):
        raise CryptoError("plaintext must be bytes")
    try:
        encrypted = _get_aead().encrypt(bytes(plaintext), PLATFORM_SENTINEL_AAD)
    except nacl.exceptions.CryptoError as exc:
        raise CryptoError("encrypt failed") from exc
    return bytes([VERSION]) + bytes(encrypted)


def decrypt_platform_sentinel(ciphertext: bytes) -> bytes:
    """Inverse of `encrypt_platform_sentinel`. Raises on tampered ciphertext,
    AAD mismatch (= wrong key), or version skew."""
    if not isinstance(ciphertext, (bytes, bytearray)):
        raise CryptoError("ciphertext must be bytes")
    if len(ciphertext) < 1 + NONCE_BYTES + MAC_BYTES:
        raise CryptoError("ciphertext too short")
    if ciphertext[0] != VERSION:
        raise CryptoError("unsupported ciphertext version")
    body = bytes(ciphertext[1:])
    try:
        return _get_aead().decrypt(body, PLATFORM_SENTINEL_AAD)
    except nacl.exceptions.CryptoError as exc:
        raise CryptoError("decrypt failed") from exc


# ---------------------------------------------------------------------------
# tenant_secrets persistence (PR-3) — put / get / rotate
# ---------------------------------------------------------------------------


def _split_wire(wire: bytes) -> tuple[bytes, bytes]:
    """Split versioned wire blob into (nonce, ciphertext_with_tag).

    Wire format: [VERSION][nonce(24)][ciphertext+tag]. Used to populate
    tenant_secrets.{nonce, ciphertext} as separate columns. The VERSION
    byte lives in tenant_secrets.version (INT column).
    """
    if len(wire) < 1 + NONCE_BYTES + MAC_BYTES:
        raise CryptoError("wire blob too short")
    if wire[0] != VERSION:
        raise CryptoError("unsupported ciphertext version")
    nonce = bytes(wire[1 : 1 + NONCE_BYTES])
    ct = bytes(wire[1 + NONCE_BYTES :])
    return nonce, ct


def _join_wire(nonce: bytes, ciphertext: bytes, version: int = VERSION) -> bytes:
    """Reconstruct the versioned wire blob expected by `decrypt()` from the
    nonce + ciphertext+tag columns persisted in tenant_secrets."""
    return bytes([version]) + bytes(nonce) + bytes(ciphertext)


async def put(
    conn: asyncpg.Connection,
    tenant_id: UUID,
    kind: str,
    plaintext: bytes,
) -> None:
    """Encrypt and upsert a tenant secret.

    The caller passes the asyncpg connection so persistence joins whatever
    transaction the caller already has open (typically a TenantContext
    request transaction). RLS gates which tenant_id rows the connection's
    role can touch — passing a different tenant_id than the SET LOCAL value
    raises an RLS error rather than a silent cross-tenant write.

    Idempotent: a second `put(...)` for the same (tenant_id, kind) updates
    in place and sets `rotated_at = now()` — same semantics as `rotate()`.
    """
    wire = encrypt(plaintext, tenant_id)
    nonce, ct = _split_wire(wire)
    await conn.execute(
        """
        INSERT INTO tenant_secrets (tenant_id, kind, ciphertext, nonce, algo, version)
        VALUES ($1, $2, $3, $4, $5, $6)
        ON CONFLICT (tenant_id, kind) DO UPDATE
        SET ciphertext = EXCLUDED.ciphertext,
            nonce      = EXCLUDED.nonce,
            algo       = EXCLUDED.algo,
            version    = EXCLUDED.version,
            rotated_at = now()
        """,
        tenant_id,
        kind,
        ct,
        nonce,
        ALGO_XCHACHA20POLY1305,
        VERSION,
    )


async def get(
    conn: asyncpg.Connection,
    tenant_id: UUID,
    kind: str,
) -> bytes | None:
    """Read + decrypt a tenant secret. Returns None if the row is absent.

    RLS already gates the SELECT; a row visible to this connection is
    therefore owned by `tenant_id`. The decrypt step re-validates that by
    re-using `tenant_id` as the AAD — a row copied across tenants would
    fail the AEAD check with `CryptoError("decrypt failed")`.
    """
    row = await conn.fetchrow(
        "SELECT nonce, ciphertext, version FROM tenant_secrets "
        "WHERE tenant_id = $1 AND kind = $2",
        tenant_id,
        kind,
    )
    if row is None:
        return None
    wire = _join_wire(row["nonce"], row["ciphertext"], int(row["version"]))
    return decrypt(wire, tenant_id)


async def rotate(
    conn: asyncpg.Connection,
    tenant_id: UUID,
    kind: str,
) -> None:
    """Re-encrypt an existing secret with a fresh nonce under the same key.

    Reads the current plaintext, then `put()`s it back — which generates a
    new nonce on the next `_get_aead().encrypt()` call and sets
    `rotated_at = now()` via the ON CONFLICT path. Raises CryptoError if
    no row exists for (tenant_id, kind).

    Note: this does NOT rotate the underlying `POLARIS_KMS_KEY` (that's a
    platform-level op requiring re-encryption of every row + a sentinel
    re-seed; see ../docs/internal-ops/RUNBOOK.md §2b). This rotates only the per-row nonce.
    """
    plaintext = await get(conn, tenant_id, kind)
    if plaintext is None:
        raise CryptoError("cannot rotate: secret missing")
    await put(conn, tenant_id, kind, plaintext)
